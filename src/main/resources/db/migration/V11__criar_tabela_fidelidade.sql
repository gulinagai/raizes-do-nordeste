CREATE TABLE fidelidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    consentimento BOOLEAN NOT NULL,
    data_consentimento TIMESTAMP WITH TIME ZONE,
    data_revogacao TIMESTAMP WITH TIME ZONE,
    saldo INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_fidelidade_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_fidelidade_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_fidelidade_saldo CHECK (saldo >= 0)
);

ALTER TABLE registro_auditoria DROP CONSTRAINT ck_auditoria_acao;

