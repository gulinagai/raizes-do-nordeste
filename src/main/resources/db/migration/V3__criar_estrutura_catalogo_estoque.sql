CREATE TABLE unidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cidade VARCHAR(80) NOT NULL,
    endereco VARCHAR(180) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    unidade_matriz_id BIGINT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_unidade_matriz FOREIGN KEY (unidade_matriz_id) REFERENCES unidade (id),
    CONSTRAINT ck_unidade_tipo CHECK (tipo IN ('MATRIZ', 'FILIAL')),
    CONSTRAINT ck_unidade_vinculo_matriz CHECK (
        (tipo = 'MATRIZ' AND unidade_matriz_id IS NULL)
        OR (tipo = 'FILIAL' AND unidade_matriz_id IS NOT NULL AND unidade_matriz_id <> id)
    )
);

CREATE UNIQUE INDEX uk_unidade_uma_matriz ON unidade (tipo) WHERE tipo = 'MATRIZ';

CREATE INDEX idx_unidade_matriz ON unidade (unidade_matriz_id);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(500),
    preco NUMERIC(10, 2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_produto_preco CHECK (preco >= 0)
);

CREATE TABLE estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade_total INTEGER NOT NULL,
    quantidade_reservada INTEGER NOT NULL,
    CONSTRAINT fk_estoque_unidade FOREIGN KEY (unidade_id) REFERENCES unidade (id),
    CONSTRAINT fk_estoque_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id),
    CONSTRAINT ck_estoque_quantidade_total CHECK (quantidade_total >= 0),
    CONSTRAINT ck_estoque_quantidade_reservada CHECK (quantidade_reservada >= 0),
    CONSTRAINT ck_estoque_reserva_nao_excede_total CHECK (quantidade_reservada <= quantidade_total)
);

CREATE INDEX idx_estoque_produto ON estoque (produto_id);

-- CHECK nao consulta outra linha. A funcao garante que a filial aponta para a unidade do tipo MATRIZ.
CREATE FUNCTION validar_vinculo_unidade()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.tipo = 'FILIAL' AND NOT EXISTS (
        SELECT 1
        FROM unidade
        WHERE id = NEW.unidade_matriz_id
          AND tipo = 'MATRIZ'
    ) THEN
        RAISE EXCEPTION 'unidade filial deve referenciar a unidade matriz';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_unidade_vinculo
BEFORE INSERT OR UPDATE ON unidade
FOR EACH ROW
EXECUTE FUNCTION validar_vinculo_unidade();
