ALTER TABLE pedido DROP CONSTRAINT ck_pedido_status;

ALTER TABLE pedido ADD CONSTRAINT ck_pedido_status
    CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'EM_PREPARO', 'PAGAMENTO_RECUSADO'));

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT uk_pagamento_pedido UNIQUE (pedido_id),
    CONSTRAINT ck_pagamento_status CHECK (status IN ('APROVADO', 'RECUSADO')),
    CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);
